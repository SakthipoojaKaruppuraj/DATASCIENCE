
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from pathlib import Path
import math

# --------------------------------------------------
# 1. PATH CONFIGURATION
# --------------------------------------------------

BASE_DIR = Path(__file__).resolve().parent.parent

DATA_PATH = BASE_DIR / "data" / "cleaned_telco_churn.csv"

PLOT_DIR = Path(__file__).resolve().parent / "plots" / "univariate_numerical"
PLOT_DIR.mkdir(parents=True, exist_ok=True)


# --------------------------------------------------
# 2. CLEAN PREVIOUS GENERATED PLOT FILES
# --------------------------------------------------

old_files = [
    *PLOT_DIR.glob("*.png"),
    *PLOT_DIR.glob("*.csv")
]

for file in old_files:
    file.unlink()

# Remove individual plots generated by the previous version
# from the parent plots directory, if they exist.

OLD_PLOT_DIR = Path(__file__).resolve().parent / "plots"

for file in OLD_PLOT_DIR.glob("univariate_hist_*.png"):
    file.unlink()

for file in OLD_PLOT_DIR.glob("univariate_box_*.png"):
    file.unlink()


# --------------------------------------------------
# 3. LOAD DATA
# --------------------------------------------------

df = pd.read_csv(DATA_PATH)

print("=" * 70)
print("UNIVARIATE NUMERICAL ANALYSIS")
print("=" * 70)

print(f"\nDataset Shape: {df.shape}")


# --------------------------------------------------
# 4. IDENTIFY NUMERICAL COLUMNS
# --------------------------------------------------

numerical_columns = df.select_dtypes(include=np.number).columns.tolist()

excluded_columns = [
    "Zip Code",
    "Latitude",
    "Longitude",
    "Population"
]

numerical_columns = [
    col for col in numerical_columns
    if col not in excluded_columns
]

print("\nNumerical Columns Selected:")

for col in numerical_columns:
    print(f"- {col}")

print(f"\nTotal Numerical Columns: {len(numerical_columns)}")


# --------------------------------------------------
# 5. DESCRIPTIVE STATISTICS
# --------------------------------------------------

print("\n" + "=" * 70)
print("DESCRIPTIVE STATISTICS")
print("=" * 70)

statistics = df[numerical_columns].describe().T

statistics["median"] = df[numerical_columns].median()
statistics["skewness"] = df[numerical_columns].skew()
statistics["missing_values"] = df[numerical_columns].isnull().sum()

print(statistics.round(2))

statistics.to_csv(
    PLOT_DIR / "numerical_statistics.csv"
)


# --------------------------------------------------
# 6. DISTRIBUTION ANALYSIS
# --------------------------------------------------

print("\n" + "=" * 70)
print("DISTRIBUTION ANALYSIS")
print("=" * 70)

for col in numerical_columns:

    skew_value = df[col].skew()

    if skew_value > 0.5:
        distribution = "Right Skewed"

    elif skew_value < -0.5:
        distribution = "Left Skewed"

    else:
        distribution = "Approximately Symmetric"

    print(
        f"{col}: Skewness = {skew_value:.2f} | "
        f"Distribution = {distribution}"
    )


# --------------------------------------------------
# 7. OUTLIER INVESTIGATION - IQR METHOD
# --------------------------------------------------

print("\n" + "=" * 70)
print("OUTLIER INVESTIGATION (IQR METHOD)")
print("=" * 70)

outlier_results = []

for col in numerical_columns:

    Q1 = df[col].quantile(0.25)
    Q3 = df[col].quantile(0.75)

    IQR = Q3 - Q1

    lower_bound = Q1 - 1.5 * IQR
    upper_bound = Q3 + 1.5 * IQR

    outliers = df[
        (df[col] < lower_bound) |
        (df[col] > upper_bound)
    ]

    outlier_count = len(outliers)

    outlier_percentage = (
        outlier_count / len(df) * 100
        if len(df) > 0 else 0
    )

    outlier_results.append({
        "Column": col,
        "Q1": Q1,
        "Q3": Q3,
        "IQR": IQR,
        "Lower Bound": lower_bound,
        "Upper Bound": upper_bound,
        "Outlier Count": outlier_count,
        "Outlier Percentage": outlier_percentage
    })

    print(
        f"{col}: {outlier_count} outliers "
        f"({outlier_percentage:.2f}%)"
    )


outlier_df = pd.DataFrame(outlier_results)

outlier_df.to_csv(
    PLOT_DIR / "numerical_outlier_summary.csv",
    index=False
)


# --------------------------------------------------
# 8. COMBINED HISTOGRAMS
# --------------------------------------------------

print("\nGenerating Combined Histograms...")

n_cols = 3
n_rows = math.ceil(len(numerical_columns) / n_cols)

fig, axes = plt.subplots(
    n_rows,
    n_cols,
    figsize=(18, 5 * n_rows)
)

axes = np.array(axes).flatten()

for i, col in enumerate(numerical_columns):

    sns.histplot(
        data=df,
        x=col,
        bins=30,
        kde=True,
        ax=axes[i]
    )

    axes[i].set_title(f"Distribution of {col}")
    axes[i].set_xlabel(col)
    axes[i].set_ylabel("Frequency")

# Remove unused subplots
for j in range(len(numerical_columns), len(axes)):
    fig.delaxes(axes[j])

fig.suptitle(
    "Univariate Numerical Analysis - Histograms",
    fontsize=18,
    fontweight="bold"
)

fig.tight_layout()

fig.savefig(
    PLOT_DIR / "numerical_histograms.png",
    dpi=300,
    bbox_inches="tight"
)

plt.close(fig)


# --------------------------------------------------
# 9. COMBINED BOXPLOTS
# --------------------------------------------------

print("\nGenerating Combined Boxplots...")

n_cols = 3
n_rows = math.ceil(len(numerical_columns) / n_cols)

fig, axes = plt.subplots(
    n_rows,
    n_cols,
    figsize=(18, 4 * n_rows)
)

axes = np.array(axes).flatten()

for i, col in enumerate(numerical_columns):

    sns.boxplot(
        data=df,
        x=col,
        ax=axes[i]
    )

    axes[i].set_title(f"Boxplot of {col}")
    axes[i].set_xlabel(col)

# Remove unused subplots
for j in range(len(numerical_columns), len(axes)):
    fig.delaxes(axes[j])

fig.suptitle(
    "Univariate Numerical Analysis - Boxplots",
    fontsize=18,
    fontweight="bold"
)

fig.tight_layout()

fig.savefig(
    PLOT_DIR / "numerical_boxplots.png",
    dpi=300,
    bbox_inches="tight"
)

plt.close(fig)


# --------------------------------------------------
# 10. FINAL VALIDATION
# --------------------------------------------------

print("\n" + "=" * 70)
print("FINAL VALIDATION")
print("=" * 70)

generated_files = list(PLOT_DIR.iterdir())

for file in generated_files:
    print(f"- {file.name}")

print(f"\nTotal Output Files: {len(generated_files)}")

print(
    f"Histograms Exists: "
    f"{(PLOT_DIR / 'numerical_histograms.png').exists()}"
)

print(
    f"Boxplots Exists: "
    f"{(PLOT_DIR / 'numerical_boxplots.png').exists()}"
)

print(
    f"Statistics Exists: "
    f"{(PLOT_DIR / 'numerical_statistics.csv').exists()}"
)

print(
    f"Outlier Summary Exists: "
    f"{(PLOT_DIR / 'numerical_outlier_summary.csv').exists()}"
)

print("\nUnivariate Numerical Analysis Completed!")
